-- ============================================================
-- コスト集計レポート
-- 実行タイミング: 最終実行から 45 分以上経過後に実行すること
-- （CORTEX_AI_FUNCTIONS_USAGE_HISTORY の反映遅延のため）
-- ============================================================

-- 1. ファイル別・関数別の実行サマリ（RUN_LOG ベース）
SELECT
    FILE_NAME,
    FUNCTION_NAME,
    MODE_OR_MODEL,
    COUNT(*)                        AS RUNS,
    ROUND(AVG(ELAPSED_SEC), 2)      AS AVG_ELAPSED_SEC,
    ROUND(SUM(ELAPSED_SEC), 2)      AS TOTAL_ELAPSED_SEC,
    ROUND(AVG(AUDIO_DURATION_SEC), 2) AS AVG_AUDIO_DURATION_SEC
FROM DB_ANALYTICS.AUDIO_POC.RUN_LOG
WHERE ERROR IS NULL
GROUP BY FILE_NAME, FUNCTION_NAME, MODE_OR_MODEL
ORDER BY FUNCTION_NAME, FILE_NAME;

-- 2. Cortex AI クレジット消費（USAGE_HISTORY との結合）
-- ※ QUERY_ID で RUN_LOG と突合
SELECT
    r.FILE_NAME,
    r.FUNCTION_NAME,
    r.MODE_OR_MODEL,
    r.QUERY_ID,
    u.CREDITS    AS CREDITS,
    u.START_TIME,
    u.END_TIME
FROM DB_ANALYTICS.AUDIO_POC.RUN_LOG r
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY u
    ON r.QUERY_ID = u.QUERY_ID
WHERE r.ERROR IS NULL
ORDER BY r.FUNCTION_NAME, r.FILE_NAME;

-- 3. 関数別コスト集計
SELECT
    r.FUNCTION_NAME,
    COUNT(*)                                    AS RUNS,
    ROUND(SUM(u.CREDITS), 6) AS TOTAL_CREDITS,
    ROUND(SUM(u.CREDITS) * 2.0, 4) AS EST_COST_USD
FROM DB_ANALYTICS.AUDIO_POC.RUN_LOG r
JOIN SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY u
    ON r.QUERY_ID = u.QUERY_ID
WHERE r.ERROR IS NULL
GROUP BY r.FUNCTION_NAME
ORDER BY TOTAL_CREDITS DESC;

-- 4. CER サマリ（カテゴリ別）
SELECT
    t.CATEGORY,
    COUNT(*)                                  AS FILES,
    ROUND(AVG(e.CER_RAW) * 100, 1)           AS AVG_CER_RAW_PCT,
    ROUND(AVG(e.CER_NORMALIZED) * 100, 1)    AS AVG_CER_NORM_PCT,
    ROUND(AVG(e.REF_CHAR_COUNT), 0)          AS AVG_REF_CHARS,
    ROUND(AVG(e.HYP_CHAR_COUNT), 0)          AS AVG_HYP_CHARS
FROM DB_ANALYTICS.AUDIO_POC.EVALUATION_RESULT e
JOIN DB_ANALYTICS.AUDIO_POC.REFERENCE_TEXT t
    ON e.FILE_NAME = t.FILE_NAME
GROUP BY t.CATEGORY
ORDER BY AVG_CER_RAW_PCT;

-- 5. CER サマリ（環境別: 静か / うるさい）
SELECT
    t.ENVIRONMENT,
    COUNT(*)                                  AS FILES,
    ROUND(AVG(e.CER_RAW) * 100, 1)           AS AVG_CER_RAW_PCT,
    ROUND(AVG(e.CER_NORMALIZED) * 100, 1)    AS AVG_CER_NORM_PCT
FROM DB_ANALYTICS.AUDIO_POC.EVALUATION_RESULT e
JOIN DB_ANALYTICS.AUDIO_POC.REFERENCE_TEXT t
    ON e.FILE_NAME = t.FILE_NAME
GROUP BY t.ENVIRONMENT
ORDER BY t.ENVIRONMENT;

-- 6. CER サマリ（声種別: 男性 / 女性）
SELECT
    t.VOICE_TYPE,
    COUNT(*)                                  AS FILES,
    ROUND(AVG(e.CER_RAW) * 100, 1)           AS AVG_CER_RAW_PCT,
    ROUND(AVG(e.CER_NORMALIZED) * 100, 1)    AS AVG_CER_NORM_PCT
FROM DB_ANALYTICS.AUDIO_POC.EVALUATION_RESULT e
JOIN DB_ANALYTICS.AUDIO_POC.REFERENCE_TEXT t
    ON e.FILE_NAME = t.FILE_NAME
GROUP BY t.VOICE_TYPE
ORDER BY t.VOICE_TYPE;

-- 7. CER クロス集計（カテゴリ × 環境 × 声種別）
SELECT
    t.CATEGORY,
    t.ENVIRONMENT,
    t.VOICE_TYPE,
    e.FILE_NAME,
    ROUND(e.CER_RAW * 100, 1)        AS CER_RAW_PCT,
    ROUND(e.CER_NORMALIZED * 100, 1) AS CER_NORM_PCT
FROM DB_ANALYTICS.AUDIO_POC.EVALUATION_RESULT e
JOIN DB_ANALYTICS.AUDIO_POC.REFERENCE_TEXT t
    ON e.FILE_NAME = t.FILE_NAME
ORDER BY t.CATEGORY, t.ENVIRONMENT, t.VOICE_TYPE;
